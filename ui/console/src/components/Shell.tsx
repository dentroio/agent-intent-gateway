// Port of the AegisFlux ConsoleShell (WO-UX-022, "Clarion-style shell"): same header, sidebar,
// breadcrumb bar and section tabs, so operators move between dentro.io consoles without relearning.
import { Moon, PanelLeftClose, PanelLeftOpen, Sun } from 'lucide-react'
import { useEffect, useState } from 'react'
import type { ReactNode } from 'react'
import { NAV, go, navFor, tabLabel, type RouteId } from '../routes'
import { cn } from './ui'

export type Health = { label: string; tone: 'emerald' | 'amber' | 'red' | 'slate'; text: string }

const SIDEBAR_KEY = 'aig_console_sidebar_open'
const THEME_KEY = 'aig_console_theme'

function useTheme(): ['light' | 'dark', () => void] {
  const [theme, setTheme] = useState<'light' | 'dark'>(
    document.documentElement.classList.contains('dark') ? 'dark' : 'light')
  const toggle = () => {
    const next = theme === 'dark' ? 'light' : 'dark'
    document.documentElement.classList.toggle('dark', next === 'dark')
    try { localStorage.setItem(THEME_KEY, next) } catch { /* private mode */ }
    setTheme(next)
  }
  return [theme, toggle]
}

export function Logo() {
  return (
    <div className="flex h-9 w-9 items-center justify-center overflow-hidden rounded-lg bg-slate-950">
      <svg viewBox="0 0 36 36" className="h-7 w-7" aria-hidden>
        <rect x="7" y="7" width="5" height="22" rx="1.5" fill="#1d9bff" />
        <rect x="24" y="7" width="5" height="22" rx="1.5" fill="#1d9bff" />
        <path d="M3 18h14m0 0-4-4m4 4-4 4" stroke="#e2e8f0" strokeWidth="2.2" fill="none" strokeLinecap="round" strokeLinejoin="round" />
        <path d="M19 18h14" stroke="#2dd4bf" strokeWidth="2.2" strokeLinecap="round" />
      </svg>
    </div>
  )
}

export function Shell({ route, health, demo, approvalsWaiting, operator, children }: {
  route: RouteId; health: Health; demo: boolean; approvalsWaiting: number; operator: string; children: ReactNode
}) {
  const [theme, toggleTheme] = useTheme()
  const [sidebarOpen, setSidebarOpen] = useState(() => {
    try { const v = sessionStorage.getItem(SIDEBAR_KEY); if (v) return v === 'true' } catch { /* ignore */ }
    return window.innerWidth >= 768
  })
  useEffect(() => { try { sessionStorage.setItem(SIDEBAR_KEY, String(sidebarOpen)) } catch { /* ignore */ } }, [sidebarOpen])

  const active = navFor(route)
  const tab = tabLabel(route)
  const dot = { emerald: 'bg-emerald-500', amber: 'bg-amber-400', red: 'bg-red-500', slate: 'bg-slate-400' }[health.tone]

  const navigate = (r: RouteId) => {
    go(r)
    if (window.innerWidth < 768) setSidebarOpen(false)
  }

  return (
    <div className="flex h-screen flex-col bg-gray-50 font-sans dark:bg-gray-950">
      <header className="z-10 flex-shrink-0 border-b border-gray-200 bg-white shadow-sm dark:border-gray-700 dark:bg-gray-800"
        style={{ paddingTop: 'env(safe-area-inset-top, 0px)', paddingLeft: 'env(safe-area-inset-left, 0px)', paddingRight: 'env(safe-area-inset-right, 0px)' }}>
        <div className="flex h-16 items-center justify-between gap-3 px-4">
          <button type="button" onClick={() => navigate('overview')} className="flex shrink-0 items-center gap-3">
            <Logo />
            <span className="text-xl font-extrabold leading-none tracking-tight text-slate-950 dark:text-white">
              Intent<span className="text-blue-600 dark:text-blue-400">Gateway</span>
            </span>
          </button>
          <div className="flex min-w-0 items-center gap-3">
            <button type="button" onClick={toggleTheme}
              className="flex h-9 w-9 items-center justify-center rounded-lg text-gray-500 transition-colors hover:bg-slate-100 hover:text-gray-900 dark:text-gray-300 dark:hover:bg-gray-700 dark:hover:text-gray-100"
              title={`Switch to ${theme === 'light' ? 'dark' : 'light'} mode`} aria-label={`Switch to ${theme === 'light' ? 'dark' : 'light'} mode`}>
              {theme === 'light' ? <Moon size={20} /> : <Sun size={20} />}
            </button>
            {demo ? (
              <span className="hidden h-7 items-center rounded-md border border-amber-200 bg-amber-50 px-2 text-xs font-semibold text-amber-800 dark:border-amber-700 dark:bg-amber-900/30 dark:text-amber-200 sm:inline-flex"
                title="Traffic generated by running the red-team library through the gateway">
                Demo data
              </span>
            ) : null}
            <div className="flex min-w-0 items-center gap-2 border-l border-gray-200 pl-2 dark:border-gray-600" title={health.text}>
              <span className={cn('h-2.5 w-2.5 shrink-0 rounded-full', dot)} />
              <span className="truncate text-sm font-medium text-slate-700 dark:text-gray-200">{health.label}</span>
            </div>
            <div className="hidden items-center gap-2 border-l border-gray-200 pl-2 dark:border-gray-600 md:flex">
              <span className="text-sm font-medium text-gray-700 dark:text-gray-200" title="Signed in at the gateway">{operator}</span>
            </div>
          </div>
        </div>
      </header>

      <div className="relative flex min-h-0 flex-1">
        <aside className={cn('flex-shrink-0 border-r border-gray-200 bg-white transition-all duration-200 dark:border-gray-700 dark:bg-gray-800',
          sidebarOpen ? 'w-60 overflow-y-auto' : 'w-0 overflow-hidden',
          'max-md:absolute max-md:inset-y-0 max-md:left-0 max-md:z-30 max-md:shadow-xl')}>
          <nav className="w-60 space-y-1 p-4" aria-label="Main navigation" style={{ paddingLeft: 'max(1rem, env(safe-area-inset-left, 0px))' }}>
            {NAV.map((group) => (
              <div key={group.label} className="space-y-1">
                <div className="px-3 pb-1 pt-5 first:pt-1">
                  <span className="select-none text-xs font-semibold uppercase tracking-wider text-gray-500 dark:text-gray-400">{group.label}</span>
                </div>
                {group.items.map((item) => {
                  const Icon = item.icon
                  const isActive = item.id === active.id
                  return (
                    <button key={item.id} type="button" onClick={() => navigate(item.route)} aria-current={isActive ? 'page' : undefined}
                      className={cn('flex w-full items-center gap-3 rounded-lg px-4 py-2.5 text-sm font-medium transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-primary-500',
                        isActive ? 'bg-clarion-blue text-white' : 'text-gray-700 hover:bg-gray-100 dark:text-gray-300 dark:hover:bg-gray-700')}>
                      <Icon className="h-5 w-5 shrink-0" />
                      <span className="truncate">{item.label}</span>
                      {item.id === 'activity' && approvalsWaiting > 0 ? (
                        <span title={`${approvalsWaiting} calls were refused for want of approval`}
                          className={cn('ml-auto rounded-full px-2 py-0.5 text-xs font-semibold',
                            isActive ? 'bg-white text-clarion-blue' : 'bg-amber-100 text-amber-800 dark:bg-amber-900/40 dark:text-amber-200')}>
                          {approvalsWaiting}
                        </span>
                      ) : null}
                    </button>
                  )
                })}
              </div>
            ))}
          </nav>
        </aside>
        {sidebarOpen ? <button type="button" aria-label="Close navigation" className="absolute inset-0 z-20 bg-slate-900/20 md:hidden" onClick={() => setSidebarOpen(false)} /> : null}

        <div className="flex min-h-0 min-w-0 flex-1 flex-col overflow-hidden">
          <div className="flex flex-shrink-0 items-stretch border-b border-gray-100 bg-white dark:border-gray-800 dark:bg-gray-800">
            <button type="button" onClick={() => setSidebarOpen((o) => !o)}
              className="flex w-10 shrink-0 items-center justify-center border-r border-gray-100 text-gray-400 transition-colors hover:bg-gray-50 hover:text-gray-700 dark:border-gray-700 dark:hover:bg-gray-700/50 dark:hover:text-gray-200"
              aria-label={sidebarOpen ? 'Collapse navigation' : 'Expand navigation'}>
              {sidebarOpen ? <PanelLeftClose size={14} /> : <PanelLeftOpen size={14} />}
            </button>
            <nav aria-label="Breadcrumb" className="flex min-w-0 items-center gap-1.5 px-4 py-2 text-sm text-gray-500 dark:text-gray-400">
              {route === 'overview' ? <span className="font-medium text-gray-900 dark:text-gray-100">Overview</span> : (
                <>
                  <button type="button" onClick={() => navigate('overview')} className="hover:text-gray-700 dark:hover:text-gray-200">Overview</button>
                  <span className="text-gray-300 dark:text-gray-600">›</span>
                  {tab ? (
                    <>
                      <button type="button" onClick={() => navigate(active.route)} className="font-medium text-blue-600 hover:text-blue-800 dark:text-blue-400">{active.label}</button>
                      <span className="text-gray-300 dark:text-gray-600">›</span>
                      <span className="truncate font-medium text-gray-900 dark:text-gray-100">{tab}</span>
                    </>
                  ) : <span className="font-medium text-gray-900 dark:text-gray-100">{active.label}</span>}
                </>
              )}
            </nav>
          </div>

          <main className="min-h-0 flex-1 overflow-y-auto" style={{ paddingBottom: 'env(safe-area-inset-bottom, 0px)', paddingRight: 'env(safe-area-inset-right, 0px)' }}>
            {active.tabs ? (
              <div className="border-b border-gray-200 bg-white px-4 dark:border-gray-700 dark:bg-gray-800 sm:px-5 lg:px-6">
                <nav className="flex flex-wrap gap-1" role="tablist" aria-label={`${active.label} section`}>
                  {active.tabs.map((t) => (
                    <button key={t.id} type="button" role="tab" aria-selected={t.id === route} onClick={() => navigate(t.id)}
                      className={cn('inline-flex items-center gap-1.5 border-b-2 px-3.5 py-2.5 text-sm font-medium transition-colors',
                        t.id === route ? 'border-blue-600 text-blue-600 dark:border-blue-400 dark:text-blue-400'
                          : 'border-transparent text-gray-500 hover:text-gray-900 dark:text-gray-400 dark:hover:text-gray-100')}>
                      {t.label}
                      {t.id === 'approvals' && approvalsWaiting > 0 ? (
                        <span className="rounded-full bg-amber-100 px-1.5 py-0.5 text-[10px] font-semibold text-amber-800 dark:bg-amber-900/40 dark:text-amber-200">{approvalsWaiting}</span>
                      ) : null}
                    </button>
                  ))}
                </nav>
              </div>
            ) : null}
            {children}
          </main>
        </div>
      </div>
    </div>
  )
}
